#!/usr/bin/env python3
"""After export_world.py: copy thumbnails/icons, convert every PNG layer to WebP (lossy q88 + alpha), point the
manifest at the .webp files, and delete the PNGs.  usage: python3 scripts/world_export_webp.py design/world/export/v1"""
import glob, json, os, shutil, subprocess, sys

D = os.path.abspath(sys.argv[1])
root = os.path.dirname(os.path.dirname(os.path.dirname(D)))          # design/world
for src, dst in (("room/thumbs", "thumbs"), ("yard/thumbs", "thumbs"), ("garden/icons", "icons")):
    os.makedirs(os.path.join(D, dst), exist_ok=True)
    for p in glob.glob(os.path.join(root, "world", src, "*.png")):
        shutil.copy(p, os.path.join(D, dst))
shutil.rmtree(os.path.join(D, "_tmp"), ignore_errors=True)
for p in glob.glob(os.path.join(D, "**", "*.png"), recursive=True):
    if os.path.basename(p).startswith("_"):
        continue
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", p, "-c:v", "libwebp", "-lossless", "0", "-q:v", "88",
                    "-pix_fmt", "yuva420p", p[:-4] + ".webp"], check=True)
    os.remove(p)

m = json.load(open(os.path.join(D, "manifest.json")))
def fix(o):
    if isinstance(o, dict): return {k: fix(v) for k, v in o.items()}
    if isinstance(o, list): return [fix(v) for v in o]
    if isinstance(o, str) and o.endswith(".png") and "/" in o: return o[:-4] + ".webp"
    return o
m = fix(m)
m["shop_thumbnails"] = {os.path.basename(p)[:-5]: f"thumbs/{os.path.basename(p)}" for p in sorted(glob.glob(os.path.join(D, "thumbs", "*.webp")))}
m["icons"] = {os.path.basename(p)[:-5]: f"icons/{os.path.basename(p)}" for p in sorted(glob.glob(os.path.join(D, "icons", "*.webp")))}
m["format"] = "WebP (lossy q88 + alpha). PNG masters are regenerated by the scripts, not stored here."
json.dump(m, open(os.path.join(D, "manifest.json"), "w"), ensure_ascii=False, indent=1)
missing = []
def walk(o):
    if isinstance(o, dict): [walk(v) for v in o.values()]
    elif isinstance(o, list): [walk(v) for v in o]
    elif isinstance(o, str) and o.endswith(".webp") and not os.path.exists(os.path.join(D, o)): missing.append(o)
walk(m)
print("webp:", len(glob.glob(os.path.join(D, "**", "*.webp"), recursive=True)), "missing:", missing)
